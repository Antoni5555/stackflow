const PG_DATA = '/var/lib/postgresql/data';

/** Строки лога со временем: каждая следующая — на пару миллисекунд позже. */
class Log {
  constructor(container, start = now()) {
    this.container = container;
    this.time = start;
  }

  line(text, err = false, step = 1) {
    this.time += step;
    this.container.logs.push({ t: this.time, err, text });
  }

  lines(text, err = false) {
    for (const line of text.split('\n')) this.line(line, err, 0);
  }
}

const pgTime = (ms) => {
  const p = utcParts(ms);
  return `${p.year}-${p.month}-${p.day} ${p.time}.${p.millis} UTC`;
};
const nginxTime = (ms) => {
  const p = utcParts(ms);
  return `${p.year}/${p.month}/${p.day} ${p.time}`;
};
const redisTime = (ms) => {
  const p = utcParts(ms);
  return `${p.day} ${p.monthName} ${p.year} ${p.time}.${p.millis}`;
};

const envValue = (container, name) => container.env
  .find((item) => item.startsWith(`${name}=`))?.slice(name.length + 1);

// --- postgres ---

function pgInitialized(fs) {
  try {
    fs.readFile(`${PG_DATA}/PG_VERSION`);
    return true;
  } catch (e) {
    if (e instanceof FsError) return false;
    throw e;
  }
}

function pgInitFiles(fs) {
  const own = (node) => Object.assign(node, { owner: 'postgres', group: 'postgres' });
  own(fs.mkdirAs(PG_DATA, 'root')).mode = 0o700;
  for (const dir of ['base', 'global', 'pg_wal', 'pg_xact', 'pg_stat', 'pg_tblspc']) own(fs.mkdirAs(`${PG_DATA}/${dir}`, 'root')).mode = 0o700;
  const files = {
    PG_VERSION: '16\n',
    'postgresql.conf': "# PostgreSQL configuration file\nlisten_addresses = '*'\nmax_connections = 100\nshared_buffers = 128MB\n",
    'pg_hba.conf': '# TYPE  DATABASE        USER            ADDRESS                 METHOD\nlocal   all             all                                     trust\nhost    all             all             127.0.0.1/32            trust\nhost    all             all             ::1/128                 trust\nhost all all all scram-sha-256\n',
    'pg_ident.conf': '# MAPNAME       SYSTEM-USERNAME         PG-USERNAME\n',
    'postgresql.auto.conf': '# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n',
    'postmaster.opts': '/usr/lib/postgresql/16/bin/postgres\n',
  };
  for (const [name, text] of Object.entries(files)) {
    own(fs.writeFile(`${PG_DATA}/${name}`, text)).mode = 0o600;
  }
}

