  log.line(`${t('C')} * oO0OoO0OoO0Oo Redis is starting oO0OoO0OoO0Oo`);
  log.line(`${t('C')} * Redis version=7.4.11, bits=64, commit=00000000, modified=0, pid=1, just started`);
  log.line(`${t('C')} # Warning: no config file specified, using the default config. In order to specify a config file use redis-server /path/to/redis.conf`);
