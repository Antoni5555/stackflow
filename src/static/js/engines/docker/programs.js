function stopPostgres(container, log) {
  const t = () => pgTime(log.time);
  log.line(`${t()} [1] LOG:  received fast shutdown request`);
  log.line(`${t()} [1] LOG:  aborting any active transactions`);
  log.line(`${t()} [1] LOG:  background worker "logical replication launcher" (PID 32) exited with exit code 1`);
  log.line(`${t()} [27] LOG:  shutting down`);
  log.line(`${t()} [1] LOG:  database system is shut down`);
  return 0;
}

// --- nginx ---

function startNginx(hostFs, container, log) {
  const ipv6 = withContainerFs(hostFs, container, (fs) => {
    const path = '/etc/nginx/conf.d/default.conf';
    try {
      const text = fs.readFile(path);
      if (text.includes('listen  [::]:80;')) return 'already';
      if (!/^\s*listen\s+80;/m.test(text)) return 'changed';
      fs.writeFile(path, text.replace(/^(\s*)listen\s+80;\n/m, '$1listen       80;\n$1listen  [::]:80;\n'));
      return 'enabled';
    } catch (e) {
      if (e instanceof FsError) return 'missing';
      throw e;
    }
  });
  const entry = '/docker-entrypoint.sh';
  log.line(`${entry}: /docker-entrypoint.d/ is not empty, will attempt to perform configuration`);
  log.line(`${entry}: Looking for shell scripts in /docker-entrypoint.d/`);
  log.line(`${entry}: Launching /docker-entrypoint.d/10-listen-on-ipv6-by-default.sh`);
  if (ipv6 === 'enabled') {
    log.line('10-listen-on-ipv6-by-default.sh: info: Getting the checksum of /etc/nginx/conf.d/default.conf');
    log.line('10-listen-on-ipv6-by-default.sh: info: Enabled listen on IPv6 in /etc/nginx/conf.d/default.conf');
  } else if (ipv6 === 'already') {
    log.line('10-listen-on-ipv6-by-default.sh: info: IPv6 listen already enabled');
  } else if (ipv6 === 'changed') {
    log.line('10-listen-on-ipv6-by-default.sh: info: Getting the checksum of /etc/nginx/conf.d/default.conf');
    log.line('10-listen-on-ipv6-by-default.sh: info: /etc/nginx/conf.d/default.conf differs from the packaged version');
  } else {
    log.line('10-listen-on-ipv6-by-default.sh: info: /etc/nginx/conf.d/default.conf is not a file or does not exist');
  }
  log.line(`${entry}: Sourcing /docker-entrypoint.d/15-local-resolvers.envsh`);
  log.line(`${entry}: Launching /docker-entrypoint.d/20-envsubst-on-templates.sh`);
  log.line(`${entry}: Launching /docker-entrypoint.d/30-tune-worker-processes.sh`);
  log.line(`${entry}: Configuration complete; ready for start up`);
  const t = () => nginxTime(log.time);
  const alpine = catalogImage(container.base)?.os === 'alpine';
  log.line(`${t()} [notice] 1#1: using the "epoll" event method`, true);
  log.line(`${t()} [notice] 1#1: nginx/1.27.5`, true);
  log.line(`${t()} [notice] 1#1: built by gcc ${alpine ? '14.2.0 (Alpine 14.2.0) ' : '12.2.0 (Debian 12.2.0-14) '}`, true);
  log.line(`${t()} [notice] 1#1: OS: Linux 6.8.0-87-generic`, true);
  log.line(`${t()} [notice] 1#1: getrlimit(RLIMIT_NOFILE): 1048576:1048576`, true);
  log.line(`${t()} [notice] 1#1: start worker processes`, true);
  log.line(`${t()} [notice] 1#1: start worker process 29`, true);
  log.line(`${t()} [notice] 1#1: start worker process 30`, true);
  return {
    listen: [80],
    procs: [
      { pid: 1, user: 'root', comm: 'nginx', cmd: 'nginx: master process nginx -g daemon off;' },
      { pid: 29, user: 'nginx', comm: 'nginx', cmd: 'nginx: worker process' },
      { pid: 30, user: 'nginx', comm: 'nginx', cmd: 'nginx: worker process' },
    ],
  };
}

function stopNginx(container, log) {
  const t = () => nginxTime(log.time);
  log.line(`${t()} [notice] 1#1: signal 3 (SIGQUIT) received, shutting down`, true);
  for (const pid of [29, 30]) {
    log.line(`${t()} [notice] ${pid}#${pid}: gracefully shutting down`, true);
    log.line(`${t()} [notice] ${pid}#${pid}: exiting`, true);
    log.line(`${t()} [notice] ${pid}#${pid}: exit`, true);
  }
  log.line(`${t()} [notice] 1#1: signal 17 (SIGCHLD) received from 29`, true);
  log.line(`${t()} [notice] 1#1: worker process 29 exited with code 0`, true);
  log.line(`${t()} [notice] 1#1: worker process 30 exited with code 0`, true);
  log.line(`${t()} [notice] 1#1: exit`, true);
  return 0;
}

// --- redis ---

function startRedis(hostFs, container, log) {
  const t = (role = 'M') => `1:${role} ${redisTime(log.time)}`;
  log.line(`${t('C')} # WARNING Memory overcommit must be enabled! Without it, a background save or replication may fail under low memory condition. Being disabled, it can also cause failures without low memory condition, see https://github.com/jemalloc/jemalloc/issues/1328. To fix this issue add 'vm.overcommit_memory = 1' to /etc/sysctl.conf and then reboot or run the command 'sysctl vm.overcommit_memory=1' for this to take effect.`);
  log.line(`${t('C')} * oO0OoO0OoO0Oo Redis is starting oO0OoO0OoO0Oo`);
  log.line(`${t('C')} * Redis version=7.4.11, bits=64, commit=00000000, modified=0, pid=1, just started`);
  log.line(`${t('C')} # Warning: no config file specified, using the default config. In order to specify a config file use redis-server /path/to/redis.conf`);
  log.line(`${t()} * monotonic clock: POSIX clock_gettime`);
  log.line(`${t()} * Running mode=standalone, port=6379.`);
  log.line(`${t()} * Server initialized`);
  log.line(`${t()} * Ready to accept connections tcp`);
  return { listen: [6379], procs: [{ pid: 1, user: 'redis', comm: 'redis-server', cmd: 'redis-server *:6379' }] };
}

function stopRedis(container, log) {
  log.line(`1:signal-handler (${Math.floor(log.time / 1000)}) Received SIGTERM scheduling shutdown...`);
  log.line(`1:M ${redisTime(log.time)} * User requested shutdown...`);
  log.line(`1:M ${redisTime(log.time)} * Saving the final RDB snapshot before exiting.`);
  log.line(`1:M ${redisTime(log.time)} * DB saved on disk`);
  log.line(`1:M ${redisTime(log.time)} # Redis is now ready to exit, bye bye...`);
  return 0;
}

const PROGRAMS = {
  postgres: { start: startPostgres, stop: stopPostgres, command: 'postgres' },
  nginx: { start: startNginx, stop: stopNginx, command: 'nginx' },
  redis: { start: startRedis, stop: stopRedis, command: 'redis-server' },
};

/** Главная программа контейнера: из образа, если команду не переопределили (или это она же). */
export function programOf(container) {
  const program = PROGRAMS[catalogImage(container.base)?.program];
  if (!program) return null;
  const [first] = container.cmd;
  return !first || first === program.command ? program : null;
}

/**
 * Запуск главного процесса. Возвращает {exit} — процесс сразу завершился (код), или
 * {listen, procs} — работает. Логи дописываются в container.logs.
 */
export function startProgram(hostFs, container, { first }) {
  const log = new Log(container);
  const program = programOf(container);
  if (program) return program.start(hostFs, container, log, { first });
  return null;
}

/** Остановка: логи и код выхода (137 — не завершился за 10 секунд и убит). */
export function stopProgram(container) {
  const program = programOf(container);
  if (program) return program.stop(container, new Log(container));
  return container.idle ? 137 : 0;
}

// --- HTTP к контейнеру ---

const NGINX_SERVER = 'nginx/1.27.5';

function nginxPage(code, title) {
  return `<html>\r\n<head><title>${code} ${title}</title></head>\r\n<body>\r\n<center><h1>${code} ${title}</h1></center>\r\n<hr><center>${NGINX_SERVER}</center>\r\n</body>\r\n</html>\r\n`;
}

/** Ответ nginx из контейнера: файлы из root (по умолчанию /usr/share/nginx/html). */
export function nginxAnswer(hostFs, container, request) {
  const root = withContainerFs(hostFs, container, (fs) => {
    try {
      const conf = fs.readFile('/etc/nginx/conf.d/default.conf');
      return /root\s+([^;]+);/.exec(conf)?.[1].trim() ?? '/usr/share/nginx/html';
    } catch (e) {
      return '/usr/share/nginx/html';
    }
  });
  let path = normalize(request.path.split('?')[0]);
  if (request.path.endsWith('/')) path = normalize(`${path}/index.html`);
  const file = withContainerFs(hostFs, container, (fs) => fs.as('nginx', () => {
    try {
      return { body: fs.readFile(normalize(`${root}/${path}`)) };
    } catch (e) {
      if (e instanceof FsError) return { code: e.code === 'EACCES' ? 403 : 404 };
      throw e;
    }
  }));
  const code = file.body !== undefined ? 200 : file.code;
  const body = file.body ?? nginxPage(code, code === 403 ? 'Forbidden' : 'Not Found');
  const type = !file.body ? 'text/html' : path.endsWith('.css') ? 'text/css' : path.endsWith('.js') ? 'application/javascript'
    : path.endsWith('.json') ? 'application/json' : /\.html?$/.test(path) ? 'text/html' : 'application/octet-stream';
  const ip = request.client ?? '172.17.0.1';
  const p = utcParts(now());
  container.logs.push({ t: now(), err: false, text: `${ip} - - [${p.day}/${p.monthName}/${p.year}:${p.time} +0000] "${request.method} ${request.path} HTTP/1.1" ${code} ${request.method === 'HEAD' ? 0 : new TextEncoder().encode(body).length} "-" "curl/8.5.0" "-"` });
  return {
    code,
    headers: [['Server', NGINX_SERVER], ['Date', new Date(now()).toUTCString()], ['Content-Type', type],
      ['Content-Length', String(new TextEncoder().encode(body).length)], ['Connection', 'keep-alive']],
    body,
  };
}

